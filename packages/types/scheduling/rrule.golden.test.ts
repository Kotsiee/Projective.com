Deno.test("the golden set is at least 40 hand-computed cases", () => {
	if (GOLDEN.length < 40) throw new Error(`only ${GOLDEN.length} golden cases`);
});

for (const g of GOLDEN) {
	Deno.test(`golden: ${g.name}`, () => {
		const parsed = parseRRule(g.rrule);
		if (!parsed.ok) throw new Error(`${g.rrule} refused: ${parsed.reason}`);
		const range = { from: IsoDate.parse(g.from), to: IsoDate.parse(g.to) };
		assertEquals(expandRRule(parsed.value, IsoDate.parse(g.startsOn), range, g.cap), g.expected);
	});
}
