/** One application's artwork. `draw` hands out a fresh VNode per render, as `brand-marks.tsx` explains. */
interface SoftwareArt {
	view: string;
	draw: () => JSX.Element;
}

/** A 24-unit drawing at two-thirds of the tile, where a solid mark sits level with a family glyph. */
const TILE_VIEW = "-6 -6 36 36";

/** A one-colour drawing, in the tile's ink. */
function inked(d: string, view = TILE_VIEW): SoftwareArt {
	return { view, draw: () => <path fill="currentColor" d={d} /> };
}

/**
 * Plain letters, where no drawing may ship. Adobe's trademark terms refuse its marks without
 * permission, which is why Simple Icons removed them in 14.0.0, and 3ds Max and ZBrush publish no path.
 */
function lettered(letters: string): SoftwareArt {
	return {
		view: "0 0 24 24",
		draw: () => (
			<text x="12" y="12" dy=".35em" text-anchor="middle" font-size="11.5" fill="currentColor">
				{letters}
			</text>
		),
	};
}

